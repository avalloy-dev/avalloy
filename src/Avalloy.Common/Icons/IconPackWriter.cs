using System.Buffers;
using System.Text;
using System.Text.Json;

namespace Avalloy.Icons.Baking;

/// <summary>Knobs for the emitted pack resource dictionary, so the same writer serves
/// Avalloy and any consuming app (which supplies its own control CLR namespace).</summary>
public sealed record IconPackWriterOptions
{
    /// <summary>CLR namespace of the <c>IconGlyph</c> control, for the <c>xmlns:ic</c>
    /// (e.g. <c>Avalloy.Icons</c>).</summary>
    public string ControlNamespace { get; init; } = "Avalloy.Icons";

    /// <summary>The resource element's local name (the <c>IconGlyph</c> model type).</summary>
    public string ElementName { get; init; } = "IconGlyph";

    /// <summary>Prefix on each <c>x:Key</c> — the renderer looks up
    /// <c>{KeyPrefix}{iconId}</c>. Must match the control's lookup.</summary>
    public string KeyPrefix { get; init; } = "Icon.";

    /// <summary>xmlns prefix bound to <see cref="ControlNamespace"/>.</summary>
    public string XmlnsPrefix { get; init; } = "ic";

    /// <summary>Compile the dictionary to this class (<c>x:Class</c>), e.g.
    /// <c>Avalloy.Icons.LucideIcons</c>, so an app constructs it directly instead of loading
    /// the XAML by URI at runtime — which trimming and Native AOT cannot follow. The app
    /// supplies the partial class: <c>partial class LucideIcons : ResourceDictionary</c> whose
    /// constructor calls <c>AvaloniaXamlLoader.Load(this)</c>. Null or empty = no class.</summary>
    public string? ClassName { get; init; }

    /// <summary>The compiled class's accessibility (<c>x:ClassModifier</c>), e.g.
    /// <c>internal</c>. Null or empty = public. Ignored without <see cref="ClassName"/>.</summary>
    public string? ClassModifier { get; init; }
}

/// <summary>
/// Emits the pure text artifacts of an icon pack from baked <see cref="IconGlyphSpec"/>s:
/// the Avalonia <c>ResourceDictionary</c> (<c>&lt;id&gt;.icons.axaml</c>) and the
/// <c>pack.json</c> manifest. No file I/O — returns strings the tool writes to disk.
/// </summary>
public static class IconPackWriter
{
    /// <summary>Build the <c>ResourceDictionary</c> XAML for a pack. Icons are emitted in
    /// the given order; each becomes one <c>&lt;ic:IconGlyph x:Key="{prefix}{id}" …/&gt;</c>.</summary>
    public static string WriteResourceDictionary(
        IEnumerable<KeyValuePair<string, IconGlyphSpec>> icons,
        IconPackWriterOptions? options = null)
    {
        var o = options ?? new IconPackWriterOptions();
        var sb = new StringBuilder();
        sb.AppendLine("<ResourceDictionary xmlns=\"https://github.com/avaloniaui\"");
        sb.AppendLine("                    xmlns:x=\"http://schemas.microsoft.com/winfx/2006/xaml\"");
        sb.Append($"                    xmlns:{o.XmlnsPrefix}=\"using:{o.ControlNamespace}\"");
        if (!string.IsNullOrEmpty(o.ClassName))
        {
            sb.AppendLine();
            sb.Append($"                    x:Class=\"{o.ClassName}\"");
            if (!string.IsNullOrEmpty(o.ClassModifier))
            {
                sb.AppendLine();
                sb.Append($"                    x:ClassModifier=\"{o.ClassModifier}\"");
            }
        }
        sb.AppendLine(">");
        sb.AppendLine("    <!-- GENERATED by Avalloy.IconTool. Do not hand-edit; it re-bakes on build");
        sb.AppendLine("         from the pack's source SVGs. Consumed by the GlyphIcon control. -->");
        foreach (var (id, spec) in icons)
            sb.AppendLine($"    <{o.XmlnsPrefix}:{o.ElementName} {Attrs(id, spec, o)}/>");
        sb.AppendLine("</ResourceDictionary>");
        return sb.ToString();
    }

    private static string Attrs(string id, IconGlyphSpec s, IconPackWriterOptions o)
    {
        var a = new List<string> { $"x:Key=\"{o.KeyPrefix}{id}\"", $"Box=\"{Num(s.Box)}\"" };
        if (!s.Filled) a.Add("Filled=\"False\"");
        if (s.StrokeWidth > 0) a.Add($"StrokeWidth=\"{Num(s.StrokeWidth)}\"");
        a.Add($"Geometry=\"{Esc(s.Geometry)}\"");
        if (!string.IsNullOrEmpty(s.DuoPrimary)) a.Add($"DuoPrimary=\"{Esc(s.DuoPrimary)}\"");
        if (!string.IsNullOrEmpty(s.DuoSecondary)) a.Add($"DuoSecondary=\"{Esc(s.DuoSecondary)}\"");
        if (s.Small is { } sm)
        {
            a.Add($"SmallMaxSize=\"{Num(s.SmallMaxSize)}\"");
            a.Add($"SmallBox=\"{Num(sm.Box)}\"");
            if (!sm.Filled) a.Add("SmallFilled=\"False\"");
            if (sm.StrokeWidth > 0) a.Add($"SmallStrokeWidth=\"{Num(sm.StrokeWidth)}\"");
            a.Add($"SmallGeometry=\"{Esc(sm.Geometry)}\"");
            if (!string.IsNullOrEmpty(sm.DuoPrimary)) a.Add($"SmallDuoPrimary=\"{Esc(sm.DuoPrimary)}\"");
            if (!string.IsNullOrEmpty(sm.DuoSecondary)) a.Add($"SmallDuoSecondary=\"{Esc(sm.DuoSecondary)}\"");
        }
        return string.Join(" ", a);
    }

    /// <summary>Build a <c>pack.json</c> manifest (the shape <c>IconResolver</c> reads):
    /// id/name/description/homepage/version plus the authoritative <c>icons</c> list.</summary>
    public static string WritePackJson(
        string id,
        string name,
        IEnumerable<string> iconIds,
        string? description = null,
        string? homepage = null,
        string? version = null)
    {
        // Written by hand rather than serialized from a dictionary: it needs no reflection, so the
        // baker runs trimmed or Native AOT. The bytes are what JsonSerializer wrote before (same
        // encoder, indentation and newline), so a re-bake does not churn the checked-in pack.json.
        var buffer = new ArrayBufferWriter<byte>();
        using (var w = new Utf8JsonWriter(buffer, new JsonWriterOptions { Indented = true }))
        {
            w.WriteStartObject();
            w.WriteString("id", id);
            w.WriteString("name", name);
            if (description is not null) w.WriteString("description", description);
            if (homepage is not null) w.WriteString("homepage", homepage);
            if (version is not null) w.WriteString("version", version);
            w.WriteStartArray("icons");
            foreach (var icon in iconIds) w.WriteStringValue(icon);
            w.WriteEndArray();
            w.WriteEndObject();
        }
        return Encoding.UTF8.GetString(buffer.WrittenSpan);
    }

    // Avalonia's built-in Geometry converter parses the path data, so only '&' needs
    // escaping for XAML attribute safety (the data contains no <, >, or quotes).
    private static string Esc(string s) => s.Replace("&", "&amp;");

    private static string Num(double d) => d.ToString("0.######", System.Globalization.CultureInfo.InvariantCulture);
}
